# 1. Считываем расстояние в см (используем float для дробных чисел)
cm = float(input("Введите расстояние в см: "))

# 2. Переводим последовательно по цепочке соотношений
inches = cm / 2.54
feet = inches / 12
yards = feet / 3
miles = yards / 1760

# 3. Выводим результат строго в том порядке и формате, как в примере
print(f"{yards} ярдов")
print(f"{miles} мили")
print(f"{feet} футов")
print(f"{inches} дюймов")