# 1. Запрашиваем входные данные от пользователя
серебряные = int(input("Количество серебряных часов: "))
общая_стоимость = int(input("Общая стоимость часов: "))
# 2. Вычисляем количество золотых часов (в 16 раз меньше)
золотые = серебряные // 16
# 3. Находим общую стоимость серебряных часов (по 48 руб. за штуку)
стоимость_серебряных = серебряные * 48
# 4. Находим общую стоимость золотых часов
стоимость_золотых = общая_стоимость - стоимость_серебряных
# 5. Находим цену одних золотых часов
цена_золотого = стоимость_золотых // золотые
# 6. Выводим ровно одно число на экран
print(цена_золотого)