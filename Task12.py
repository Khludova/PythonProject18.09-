#Переменная, в которую пользователь введет число
one = input("Введите число:")
#Вывод после мат. операций
прибавляем_два = int(one) + 2
умнож_на_три = int(прибавляем_два)*3
минус_шесть = int(умнож_на_три)-6
делим_на_три = int(минус_шесть)/3
вычитаем = int(делим_на_три)-4
print("Результат:", int(вычитаем))